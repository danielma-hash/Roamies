export function translate(text: string): string {
  const core = text.trim();
  const direct = COPY[text] ?? COPY[core];
  if (direct !== undefined) return text.replace(core, direct);
  for (const [pattern, render] of PATTERNS) {
    const match = pattern.exec(core);
    if (match) return text.replace(core, render(...match.slice(1)));
  }
  return text;
}

